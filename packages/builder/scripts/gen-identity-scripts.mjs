// packages/builder/scripts/gen-identity-scripts.mjs
// Writes packages/builder/src/vector/identity-scripts.generated.ts from the identity-marketplace blueprint of agents-marketplace
// (contracts/identity-marketplace/plutus.json), and copies the blueprint to packages/builder/test/fixtures/identity-marketplace.plutus.json.
// The module holds the UNAPPLIED scripts; identity-deployment.ts applies the deployment parameters at startup. The test
// identity-scripts.test.ts ties the module to the copy: same sha256, same rendered text, and every script hashes to the hash that the
// blueprint states.
//
// Run from any directory:
//   node packages/builder/scripts/gen-identity-scripts.mjs <path to plutus.json> <agents-marketplace commit>
// Never edit the generated module by hand. Run this script again after each blueprint change.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const MODULE_PATH = resolve(import.meta.dirname, '../src/vector/identity-scripts.generated.ts');
const FIXTURE_PATH = resolve(import.meta.dirname, '../test/fixtures/identity-marketplace.plutus.json');
export const BLUEPRINT_SOURCE = 'Apex-Fusion/agents-marketplace contracts/identity-marketplace/plutus.json';

/** The validators the builders use, by the name of the validator in the blueprint title `<module>.<validator>.<purpose>`. */
const NAMES = ['advert', 'attestation', 'config_holder', 'config_seal', 'delegation', 'escrow', 'identity', 'vault'];

/**
 * The text of the generated module for one blueprint. Pure: the same blueprint text and commit always give the same module text.
 * It refuses a blueprint that is not Plutus V3, a validator whose purposes disagree on the code, the hash or the parameters, and a
 * missing or unknown validator.
 */
export function renderIdentityScripts(blueprintText, commit) {
  if (!/^[0-9a-f]{7,40}$/.test(commit)) throw new Error(`commit must be 7 to 40 lowercase hex characters, got ${JSON.stringify(commit)}`);
  const blueprint = JSON.parse(blueprintText);
  if (blueprint?.preamble?.plutusVersion !== 'v3') throw new Error('the blueprint is not Plutus V3');
  const sha256 = createHash('sha256').update(blueprintText, 'utf8').digest('hex');
  const scripts = new Map();
  for (const v of blueprint.validators ?? []) {
    const [module, name, purpose] = String(v.title).split('.');
    if (!module || !name || !purpose) throw new Error(`unexpected validator title ${JSON.stringify(v.title)}`);
    if (!NAMES.includes(name)) throw new Error(`unknown validator ${JSON.stringify(v.title)}`);
    const parameters = (v.parameters ?? []).map((p) => String(p.title));
    const entry = scripts.get(name);
    if (!entry) {
      scripts.set(name, { validator: `${module}.${name}`, hash: v.hash, parameters, purposes: purpose === 'else' ? [] : [purpose], compiledCode: v.compiledCode });
      continue;
    }
    if (entry.validator !== `${module}.${name}` || entry.hash !== v.hash || entry.compiledCode !== v.compiledCode || entry.parameters.join() !== parameters.join()) {
      throw new Error(`the purposes of ${name} disagree on the module, the code, the hash or the parameters`);
    }
    if (purpose !== 'else') entry.purposes.push(purpose);
  }
  for (const name of NAMES) if (!scripts.has(name)) throw new Error(`the blueprint has no validator ${name}`);
  const p = blueprint.preamble;
  const lines = [
    '// packages/builder/src/vector/identity-scripts.generated.ts',
    '// GENERATED by packages/builder/scripts/gen-identity-scripts.mjs. Do not edit by hand: run the script again after a blueprint change.',
    `// Source: ${BLUEPRINT_SOURCE} at commit ${commit}.`,
    '// The scripts are UNAPPLIED. identity-deployment.ts applies the deployment parameters (Part 2 Section 2).',
    '',
    'export const IDENTITY_BLUEPRINT = {',
    `  source: ${JSON.stringify(BLUEPRINT_SOURCE)},`,
    `  commit: ${JSON.stringify(commit)},`,
    `  sha256: ${JSON.stringify(sha256)},`,
    `  title: ${JSON.stringify(p.title)},`,
    `  version: ${JSON.stringify(p.version)},`,
    `  compiler: ${JSON.stringify(`${p.compiler?.name} ${p.compiler?.version}`)},`,
    `  plutusVersion: ${JSON.stringify(p.plutusVersion)},`,
    '} as const;',
    '',
    'export interface UnappliedScript {',
    '  /** `<module>.<validator>` of the blueprint title. */',
    '  readonly validator: string;',
    '  /** The script hash of the unapplied script, as the blueprint states it. */',
    '  readonly hash: string;',
    '  /** The parameter names, in the order in which they are applied. */',
    '  readonly parameters: readonly string[];',
    '  /** The purposes that the validator handles; every other purpose fails. */',
    '  readonly purposes: readonly string[];',
    '  /** The compiled code (CBOR hex), as the blueprint states it. */',
    '  readonly compiledCode: string;',
    '}',
    '',
    'export type IdentityScriptName = ' + NAMES.map((n) => JSON.stringify(n)).join(' | ') + ';',
    '',
    'export const IDENTITY_SCRIPTS: Readonly<Record<IdentityScriptName, UnappliedScript>> = {',
  ];
  for (const name of NAMES) {
    const s = scripts.get(name);
    lines.push(
      `  ${name}: {`,
      `    validator: ${JSON.stringify(s.validator)},`,
      `    hash: ${JSON.stringify(s.hash)},`,
      `    parameters: [${s.parameters.map((x) => JSON.stringify(x)).join(', ')}],`,
      `    purposes: [${s.purposes.map((x) => JSON.stringify(x)).join(', ')}],`,
      `    compiledCode: ${JSON.stringify(s.compiledCode)},`,
      '  },',
    );
  }
  lines.push('};', '');
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const [blueprintPath, commit] = process.argv.slice(2);
  if (!blueprintPath || !commit) {
    console.error('usage: node packages/builder/scripts/gen-identity-scripts.mjs <path to plutus.json> <agents-marketplace commit>');
    process.exit(2);
  }
  const text = readFileSync(blueprintPath, 'utf8');
  writeFileSync(MODULE_PATH, renderIdentityScripts(text, commit));
  writeFileSync(FIXTURE_PATH, text);
  console.error(`wrote ${MODULE_PATH} and ${FIXTURE_PATH}`);
}
